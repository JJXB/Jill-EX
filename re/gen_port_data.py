"""Generate port/src/gamedata.inc from docs/profiles.json + the load modules.

The port must never hardcode episode-specific offsets.  This script emits them
from the same source the documentation uses, so the runtime table cannot drift.

Usage:  py -3 re/gen_port_data.py
"""

import json
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROFILES = os.path.join(ROOT, "docs", "profiles.json")
OUT = os.path.join(ROOT, "port", "src", "gamedata.inc")
PAL_OUT = os.path.join(ROOT, "port", "src", "palette.inc")

# DGROUP offset of the 768-byte default palette buffer (docs/jill1-engine.md).
PALETTE_DGROUP = 0x0194

FIELDS = ("width", "height", "flags", "tileset", "default_count")

# Entry counts of the per-kind handler tables in docs/profiles.json.
HANDLER_FIELD_SIZES = {
    "fly_frame": 4,
    "fly_y": 4,
    "phoenix_frame": 8,
    "phoenix_mirror": 8,
    "demon_frame": 6,
    "fatso_frame": 4,
    "expl2_frame": 8,
    "bat_frame": 4,
    "bat_y": 4,
    "snake_head": 4,
    "snake_mid": 4,
    "snake_tail": 4,
    "boll": 6,
    "knight_xoff": 11,
    "knight_frame": 11,
    "beeswarm": 32,
    "croc_head": 4,
    "croc_tail": 4,
    "skull_b": 8,
    "skull_a": 4,
    "jelly": 10,
    "badfish": 4,
}


def initializer_map(data, start):
    """Parse the kind-table initialiser (c7 06 addr value / 8c 1e addr)."""
    m = {}
    p = start
    while p < len(data) - 8:
        if data[p] in (0xC3, 0xCB):
            break
        if data[p:p + 2] == b"\xc7\x06":
            addr, val = struct.unpack_from("<HH", data, p + 2)
            m[addr] = val
            p += 6
            continue
        if data[p:p + 2] == b"\x8c\x1e":
            m[struct.unpack_from("<H", data, p + 2)[0]] = -1
            p += 4
            continue
        p += 1
    return m


def cstr(data, off):
    end = data.index(b"\x00", off)
    return data[off:end].decode("latin1")


def main():
    cfg = json.load(open(PROFILES, encoding="utf-8"))
    # The default palette lives in the load module's DGROUP image at 0x194 and
    # is identical in all three executables (checked below).  6-bit RGB.
    palettes = []
    for ep in cfg["episodes"]:
        img = open(os.path.join(ROOT, ep["image"]), "rb").read()
        base = ep["dgroup_image_base"] + PALETTE_DGROUP
        palettes.append(img[base:base + 768])
    if any(p != palettes[0] for p in palettes[1:]):
        raise SystemExit("default palettes differ between episodes")
    pal = palettes[0]
    plines = [
        "// Generated by re/gen_port_data.py - do not edit.",
        "// Default 256-colour palette (6-bit RGB) from DGROUP:0x0194.",
        "static const unsigned char kDefaultPalette[768] = {",
    ]
    for i in range(0, 768, 12):
        plines.append("    " + ", ".join("%3d" % b for b in pal[i:i + 12]) + ",")
    plines.append("};")
    plines.append("")
    open(PAL_OUT, "w", encoding="ascii", newline="\n").write("\n".join(plines))

    lines = [
        "// Generated by re/gen_port_data.py - do not edit.",
        "// Source: docs/profiles.json and the per-episode load modules.",
        "",
    ]
    for ep in cfg["episodes"]:
        n = ep["episode"]
        data = open(os.path.join(ROOT, ep["image"]), "rb").read()
        m = initializer_map(data, ep["kind_table"]["initializer_image"])
        base = ep["dgroup_image_base"]
        f = ep["kind_table"]["fields"]
        lines.append("static const KindInfo kKinds%d[] = {" % n)
        for k in range(ep["kind_count"]):
            name = cstr(data, base + m[f["name_off"] + 4 * k])
            w = m[f["width"] + 2 * k]
            h = m[f["height"] + 2 * k]
            flags = m[f["flags"] + 2 * k]
            tile = m[f["tileset"] + 2 * k]
            cnt = m[f["default_count"] + 2 * k]
            # Optional design overrides (docs/profiles.json).  These are game
            # rules, not EXE layout, so they stay in the JSON source.
            cnt = ep.get("score_overrides", {}).get(str(k), cnt)
            lines.append('    {%2d, "%s", %d, %d, 0x%04X, 0x%02X, %d},'
                         % (k, name, w, h, flags, tile, cnt))
        lines.append("};")
        lines.append("")

        # Item id -> HUD icon frame (added to 0x0E00 by the HUD).  The table
        # is identical in all episodes but lives at a different DGROUP offset.
        icon_off = base + ep["anchors"]["item_icon_table"]
        icons = struct.unpack_from("<16H", data, icon_off)
        lines.append("static const uint16_t kItemIcons%d[] = {" % n)
        lines.append("    " + ", ".join(str(v) for v in icons) + ",")
        lines.append("};")
        lines.append("")

        # Static per-kind handler tables (animation frame lists and per-frame
        # offsets copied to the handler stack in the original).  The offsets are
        # the documented DGROUP addresses of episode 1 plus this episode's
        # constant delta, so no episode-specific numbers live in the port.
        ht = cfg["handler_tables"]
        tdelta = ep.get("handler_tables_delta", 0)
        lines.append("static const HandlerTables kHandlerTables%d = {" % n)
        for field in HANDLER_FIELD_SIZES:
            size = HANDLER_FIELD_SIZES[field]
            vals = struct.unpack_from("<%dh" % size, data,
                                      base + ht[field] + tdelta)
            lines.append("    {" + ", ".join(str(v) for v in vals) + "},")
        lines.append("};")
        lines.append("")

        # Episode board list (frontend.board_list) for the port's debug
        # level select.  Names exclude the board extension.
        boards = ep["frontend"]["board_list"]
        lines.append("static const char* const kBoards%d[] = {" % n)
        lines.append("    " + ", ".join('"%s"' % b for b in boards) + ",")
        lines.append("};")
        lines.append("")

        # 36-entry level-title table (frontend.title_table): far pointers to
        # \r-separated title strings in DGROUP.  Index = level id + 4.
        tt = ep["frontend"]["title_table"]
        titles = []
        for k in range(tt["count"]):
            off = struct.unpack_from("<H", data, tt["image"] + 4 * k)[0]
            text = cstr(data, base + off).replace("\r", "\n").rstrip("\n")
            titles.append(text)
        lines.append("static const char* const kTitles%d[] = {" % n)
        for text in titles:
            esc = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            lines.append('    "%s",' % esc)
        lines.append("};")
        lines.append("")

    lines.append("static const ProfileDef kProfiles[] = {")
    for ep in cfg["episodes"]:
        n = ep["episode"]
        a = ep["anchors"]
        fr = ep["frontend"]
        lines.append("    {")
        lines.append("        %d, \"%s\", \"%s\", \"%s\", \"%s\", \"%s\", %d, kKinds%d,"
                     % (n, ep["board_extension"], fr["shape"], fr["tile_defs"],
                        fr.get("first_board") or "1", fr["intro_board"],
                        ep["kind_count"], n))
        lines.append("        %d, kItemIcons%d," % (ep["epic_score"], n))
        lines.append("        kBoards%d, %d, &kHandlerTables%d,"
                     % (n, len(fr["board_list"]), n))
        lines.append("        kTitles%d, %d," % (n, tt["count"]))
        lines.append("        \"%s\"," % ep["sound"]["bank"])
        lines.append("        \"%s\"," % fr.get("title_music", ""))
        lines.append("        {%d, %d, %d, %d, %d, %d, %d, %d, %d, %d},"
                     % (a["tile_map"], a["board_header"], a["tile_table"],
                        a["object_array"], a["object_count"], a["visible_count"],
                        a["active_list"] or 0, a["camera_ptr"],
                        a["object_max"], a["object_stride"]))
        lines.append("        \"%s\"," % ep.get("profile_id", "jill%d" % n))
        lines.append("        \"%s\", %d,"
                     % (fr.get("save_prefix", ""), fr.get("save_slots", 6)))
        lines.append("    },")
    lines.append("};")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    text = "\n".join(lines)
    open(OUT, "w", encoding="ascii", newline="\n").write(text)
    print("wrote", OUT, len(text), "bytes")


if __name__ == "__main__":
    main()
