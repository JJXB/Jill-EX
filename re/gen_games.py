"""Emit games/<id>.game manifests from docs/games.json + docs/profiles.json.

The manifests are the runtime, user-editable description of an installed game:
which asset files to load, which boards it ships, and which compiled engine
profile (kind tables, handler tables, DGROUP anchors) drives it.  A mod is a
new manifest plus a data directory; no rebuild is needed.

Fields left out of docs/games.json are filled from the profile's `frontend`
block, so the three shipped episodes need only id/title/profile/data.
"""
import json
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PROFILES = os.path.join(ROOT, "docs", "profiles.json")
GAMES = os.path.join(ROOT, "docs", "games.json")
OUTDIR = os.path.join(ROOT, "games")
PROFILEDIR = os.path.join(ROOT, "profiles")

# Shared with the compiled-data generator so the two never drift.
from gen_port_data import HANDLER_FIELD_SIZES, cstr, initializer_map


def emit_engine_profile(cfg, ep):
    """Self-contained profiles/<id>.profile, the reference a TC profile bases on."""
    n = ep["episode"]
    pid = ep.get("profile_id", "jill%d" % n)
    data = open(os.path.join(ROOT, ep["image"]), "rb").read()
    base = ep["dgroup_image_base"]
    fields = ep["kind_table"]["fields"]
    m = initializer_map(data, ep["kind_table"]["initializer_image"])

    lines = [
        "# Generated by re/gen_games.py from docs/profiles.json - do not edit.",
        "# Self-contained runtime profile.  A total conversion can inherit it:",
        "#   base = %s" % pid,
        "",
        "id = %s" % pid,
        "episode = %d" % n,
        "board_ext = %s" % ep["board_extension"],
        "save_prefix = %s" % ep["frontend"].get("save_prefix", ""),
        "save_slots = %d" % ep["frontend"].get("save_slots", 6),
        "kind_count = %d" % ep["kind_count"],
        "epic_score = %d" % ep["epic_score"],
        "object_max = %d" % ep["anchors"]["object_max"],
        "object_stride = %d" % ep["anchors"]["object_stride"],
    ]

    # Item id -> HUD icon frame.  The table lives at DGROUP:0xED4 and is
    # identical in the three episodes but at different DGROUP offsets.
    icons = [str(struct.unpack_from("<H", data, base + 0xED4 + 2 * i)[0])
             for i in range(16)]
    lines.append("item_icons = " + ", ".join(icons))

    for k in range(ep["kind_count"]):
        name = cstr(data, base + m[fields["name_off"] + 4 * k])
        cnt = ep.get("score_overrides", {}).get(str(k),
                                               m[fields["default_count"] + 2 * k])
        lines.append("kind = %d, %s, %d, %d, 0x%04X, 0x%02X, %d"
                     % (k, name, m[fields["width"] + 2 * k],
                        m[fields["height"] + 2 * k],
                        m[fields["flags"] + 2 * k],
                        m[fields["tileset"] + 2 * k],
                        cnt))

    # Level-title table (index = level id + 4), \r-separated strings in DGROUP.
    tt = ep["frontend"]["title_table"]
    for k in range(tt["count"]):
        off = struct.unpack_from("<H", data, tt["image"] + 4 * k)[0]
        text = cstr(data, base + off).replace("\r", "\n").rstrip("\n")
        if not text:
            continue
        esc = text.replace("\\", "\\\\").replace("\n", "\\n")
        lines.append("level_title = %d, %s" % (k, esc))

    ht = cfg["handler_tables"]
    tdelta = ep.get("handler_tables_delta", 0)
    for field, size in HANDLER_FIELD_SIZES.items():
        vals = struct.unpack_from("<%dh" % size, data, base + ht[field] + tdelta)
        lines.append("%s = %s" % (field, ", ".join(str(v) for v in vals)))
    # Build-specific DGROUP offsets of the same nine tables.  The runtime does
    # not need them; tools/mkprofile.py uses them to locate the block in a
    # derivative executable (the whole block shifts by one uniform delta).
    lines.append("handler_offsets = " + ", ".join(
        str(ht[field] + tdelta) for field, _ in HANDLER_FIELD_SIZES.items()))
    lines.append("dgroup_base = %d" % base)
    lines.append("")
    return pid, "\n".join(lines)


def profile_for(cfg, profile_id):
    for ep in cfg["episodes"]:
        if ep.get("profile_id", "jill%d" % ep["episode"]) == profile_id:
            return ep
    raise SystemExit("no profile named %r in docs/profiles.json" % profile_id)


def strip_ext(name, ext):
    """Manifests list board names without the extension so a mod can change
    board_ext without rewriting every key."""
    return name[:-len(ext)] if ext and name.endswith(ext) else name


def emit(game, cfg):
    ep = profile_for(cfg, game["profile"])
    fr = ep["frontend"]
    ext = game.get("board_ext", ep["board_extension"])
    data = game.get("data") or "jillt"
    boards = game.get("boards") or fr["board_list"]

    lines = [
        "# Generated by re/gen_games.py from docs/games.json - do not edit.",
        "# Copy this file, change id/title/data, and point 'boards' at your own",
        "# *.%s files to install a mod." % fr["intro_board"].rsplit(".", 1)[-1],
        "",
        "id = %s" % game["id"],
        "title = %s" % game.get("title", game["id"]),
        "profile = %s" % game["profile"],
        "data = %s" % data,
        "shapes = %s" % game.get("shapes", fr["shape"]),
        "tiles = %s" % game.get("tiles", fr["tile_defs"]),
        "pages = %s" % game.get("pages", ep["sound"]["bank"]),
        "board_ext = %s" % ext,
        "first_board = %s" % strip_ext(game.get("first_board", fr["first_board"]), ext),
        "intro_board = %s" % strip_ext(game.get("intro_board", fr["intro_board"]), ext),
    ]
    if game.get("title_music"):
        lines.append("title_music = %s" % game["title_music"])
    if game.get("save_prefix"):
        lines.append("save_prefix = %s" % game["save_prefix"])
    if game.get("save_slots") is not None:
        lines.append("save_slots = %d" % game["save_slots"])
    if game.get("palette"):
        lines.append("palette = %s" % game["palette"])
    if game.get("menu_block"):
        lines.append("menu_block = %s" % game["menu_block"])
    if game.get("suit") is not None:
        lines.append("suit = %d" % game["suit"])
    if game.get("hud_icon_bank") is not None:
        lines.append("hud_icon_bank = %d" % game["hud_icon_bank"])
    lines.append("boards = " + ", ".join(boards))
    lines.append("")
    return "\n".join(lines)


def main():
    cfg = json.load(open(PROFILES, encoding="utf-8"))
    games = json.load(open(GAMES, encoding="utf-8"))["games"]
    os.makedirs(OUTDIR, exist_ok=True)
    os.makedirs(PROFILEDIR, exist_ok=True)
    seen = set()
    for game in games:
        if game["id"] in seen:
            raise SystemExit("duplicate game id %r" % game["id"])
        seen.add(game["id"])
        path = os.path.join(OUTDIR, game["id"] + ".game")
        text = emit(game, cfg)
        open(path, "w", encoding="ascii", newline="\n").write(text)
        print("wrote", path, len(text), "bytes")

    for ep in cfg["episodes"]:
        pid, text = emit_engine_profile(cfg, ep)
        path = os.path.join(PROFILEDIR, pid + ".profile")
        open(path, "w", encoding="ascii", newline="\n").write(text)
        print("wrote", path, len(text), "bytes")


if __name__ == "__main__":
    main()
